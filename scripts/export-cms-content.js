// Writes the published CMS content into src/data/cmsContent.generated.js before the build, so the
// first render, the prerendered HTML, the metadata and the JSON-LD all come from one validated
// snapshot of what the editors published: pages, events and course passes.
//
// In CI (or with CMS_EXPORT=required) any failed, incomplete or invalid export fails the build:
// GitHub Pages then keeps serving the previous site rather than one built from partial data.
// Local builds keep the committed file (no snapshot) unless CMS_EXPORT is set.
import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import {
  REQUIRED_PAGE_SLUGS,
  fetchAllPublished,
  latestUpdate,
  projectCoursePass,
  projectEvent,
  projectPage,
} from "../src/data/cmsProjection.js";

export const TARGET = "src/data/cmsContent.generated.js";
const COLLECTIONS = ["pages", "events", "course-passes"];
const ATTEMPTS = 3;

async function newestState(cmsUrl, collection, fetchImpl) {
  const query = new URLSearchParams({ limit: "1", depth: "0", sort: "-updatedAt" });
  const response = await fetchImpl(`${cmsUrl}/api/${collection}?${query}`, { headers: { Accept: "application/json" } });
  if (!response.ok) throw new Error(`/api/${collection} svarade ${response.status}`);
  const data = await response.json();
  return { totalDocs: data?.totalDocs, newest: data?.docs?.[0]?.updatedAt || null };
}

async function readOnce(cmsUrl, fetchImpl) {
  const [pages, events, coursePasses] = await Promise.all(
    COLLECTIONS.map((collection) => fetchAllPublished(cmsUrl, collection, { fetchImpl })),
  );
  return { pages, events, "course-passes": coursePasses };
}

/**
 * Reads and validates everything. Consistency rule: after the read, the newest updatedAt and the
 * document count of each collection are asked for again; if an editor published, unpublished or
 * deleted something meanwhile, the read is repeated (up to three times) instead of mixing states.
 */
export async function exportCmsContent(cmsUrl, { fetchImpl = fetch, now = () => new Date() } = {}) {
  for (let attempt = 1; attempt <= ATTEMPTS; attempt += 1) {
    const raw = await readOnce(cmsUrl, fetchImpl);
    const after = await Promise.all(COLLECTIONS.map((collection) => newestState(cmsUrl, collection, fetchImpl)));
    const unchanged = COLLECTIONS.every((collection, index) =>
      after[index].totalDocs === raw[collection].length &&
      after[index].newest === latestUpdate(raw[collection]));
    if (!unchanged) continue;

    const pages = {};
    for (const doc of raw.pages) {
      if (typeof doc?.slug !== "string" || doc.slug === "") throw new Error(`sida ${doc?.id} saknar slug`);
      if (pages[doc.slug]) throw new Error(`två publicerade sidor har slug "${doc.slug}"`);
      pages[doc.slug] = projectPage(doc, cmsUrl);
    }
    const missing = REQUIRED_PAGE_SLUGS.filter((slug) => !pages[slug]);
    if (missing.length > 0) throw new Error(`opublicerade sidor som webbplatsen behöver: ${missing.join(", ")}`);

    const events = raw.events.map((doc) => projectEvent(doc, cmsUrl));
    const coursePasses = raw["course-passes"].map(projectCoursePass);
    return {
      exportedAt: now().toISOString(),
      revision: latestUpdate([...Object.values(pages), ...events, ...coursePasses]),
      pages,
      events,
      coursePasses,
    };
  }
  throw new Error(`innehållet ändrades under ${ATTEMPTS} exportförsök i rad`);
}

export const renderModule = (snapshot) =>
  [
    "// Generated by scripts/export-cms-content.js - do not edit by hand.",
    `export default ${JSON.stringify(snapshot, null, 2)};`,
    "",
  ].join("\n");

const runAsScript = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (runAsScript) {
  const mode = process.env.CMS_EXPORT || (process.env.CI === "true" ? "required" : "skip");
  const cmsUrl = (process.env.VITE_CMS_URL || "https://cms.storegardensju.se").replace(/\/$/, "");
  if (mode === "skip") {
    console.log(`CMS-export hoppas över lokalt; ${TARGET} används som den är (CMS_EXPORT=required för att hämta).`);
  } else {
    try {
      const snapshot = await exportCmsContent(cmsUrl);
      writeFileSync(TARGET, renderModule(snapshot));
      console.log(
        `CMS-export: ${Object.keys(snapshot.pages).length} sidor, ${snapshot.events.length} evenemang, ` +
        `${snapshot.coursePasses.length} kurstillfällen, revision ${snapshot.revision}.`,
      );
    } catch (error) {
      console.error(`CMS-export misslyckades: ${error.message}`);
      process.exit(1);
    }
  }
}
